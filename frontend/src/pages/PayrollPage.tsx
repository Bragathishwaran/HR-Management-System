function PayslipModal({
  open,
  onClose,
  payrollId,
}: {
  open: boolean;
  onClose: () => void;
  payrollId: number | null;
}) {
  const toast = useToast();
  const resource = useResource(
    (signal) => (payrollId ? endpoints.payrollDetail(payrollId) : Promise.reject(new Error("No payslip selected"))),
    [payrollId, open],
    { enabled: open && payrollId !== null },
  );

  const download = (detail: PayrollDetail) => {
    downloadPayslip(detail);
    toast.success("Payslip downloaded", `${detail.month} salary slip saved.`);
  };

  return (
    <Modal
      open={open}
      onClose={onClose}
      title="Salary slip"
      description={resource.data ? `${resource.data.month} · ${resource.data.employee_name}` : "Preparing payslip…"}
      size="lg"
      footer={
        <>
          <Button variant="secondary" onClick={onClose}>
            Close
          </Button>
          <Button
            icon={<Download size={16} />}
            disabled={!resource.data}
            onClick={() => resource.data && download(resource.data)}
          >
            Download payslip
          </Button>
        </>
      }
    >
      {resource.loading && !resource.data ? (
        <LoadingState label="Fetching payslip…" />
      ) : resource.error || !resource.data ? (
        <ErrorState message={resource.error || "Could not load payslip"} onRetry={resource.refresh} />
      ) : (
        <div className="payslip-preview">
          <div className="payslip-head">
            <div>
              <span className="payslip-brand">WorkSphere</span>
              <h3>Salary slip</h3>
            </div>
            <div className="payslip-month">
              <strong>{resource.data.month}</strong>
              <span>Slip #{String(resource.data.id).padStart(5, "0")}</span>
            </div>
          </div>
          <div className="payslip-meta">
            <div>
              <span>Employee</span>
              <strong>{resource.data.employee_name}</strong>
            </div>
            <div>
              <span>Designation</span>
              <strong>{resource.data.designation}</strong>
            </div>
            <div>
              <span>Department</span>
              <strong>{resource.data.department}</strong>
            </div>
            <div>
              <span>Generated</span>
              <strong>{formatDate(resource.data.created_at)}</strong>
            </div>
          </div>
          <div className="payslip-lines">
            <div>
              <span>Basic salary</span>
              <strong>{formatCurrency(resource.data.basic_salary)}</strong>
            </div>
            <div>
              <span>Allowances</span>
              <strong>{formatCurrency(resource.data.allowances)}</strong>
            </div>
            <div>
              <span>Bonus</span>
              <strong>{formatCurrency(resource.data.bonus)}</strong>
            </div>
            <div className="payslip-subtotal">
              <span>Gross salary</span>
              <strong>{formatCurrency(resource.data.gross_salary)}</strong>
            </div>
            <div>
              <span>Deductions</span>
              <strong className="negative">-{formatCurrency(resource.data.deductions)}</strong>
            </div>
            <div className="payslip-net">
              <span>Net pay</span>
              <strong>{formatCurrency(resource.data.net_salary)}</strong>
            </div>
          </div>
          <p className="payslip-note">
            System-generated by WorkSphere HRMS. Contact People Ops for any discrepancies.
          </p>
        </div>
      )}
    </Modal>
  );
}

function GeneratePayrollModal({
  open,
  onClose,
  employees,
  defaultMonth,
  onGenerated,
}: {
  open: boolean;
  onClose: () => void;
  employees: Employee[];
  defaultMonth: string;
  onGenerated: () => void;
}) {
  const toast = useToast();
  const [form, setForm] = useState({
    employee_id: "",
    month: defaultMonth,
    basic_salary: "",
    allowances: "0",
    bonus: "0",
    deductions: "0",
  });
  const [saving, setSaving] = useState(false);
  const [error, setError] = useState<string | null>(null);

  useEffect(() => {
    if (!open) return;
    setError(null);
    setForm({
      employee_id: "",
      month: defaultMonth,
      basic_salary: "",
      allowances: "0",
      bonus: "0",
      deductions: "0",
    });
  }, [open, defaultMonth]);

  const selectedEmployee = employees.find(
    (employee) => employee.id === Number(form.employee_id),
  );
  const basic = Number(form.basic_salary || selectedEmployee?.salary || 0);
  const net = basic + Number(form.allowances || 0) + Number(form.bonus || 0) - Number(form.deductions || 0);

  const selectEmployee = (value: string) => {
    const employee = employees.find((item) => item.id === Number(value));
    setForm((current) => ({
      ...current,
      employee_id: value,
      basic_salary: employee?.salary ? String(employee.salary) : current.basic_salary,
    }));
  };

  const submit = async (event: FormEvent) => {
    event.preventDefault();
    setError(null);
    if (net < 0) {
      setError("Deductions cannot exceed basic salary, allowances and bonus.");
      return;
    }
    setSaving(true);
    try {
      await endpoints.generatePayroll({
        employee_id: Number(form.employee_id),
        month: monthKeyFromInput(form.month),
        basic_salary: Number(form.basic_salary),
        allowances: Number(form.allowances || 0),
        bonus: Number(form.bonus || 0),
        deductions: Number(form.deductions || 0),
      });
      toast.success(
        "Payroll generated",
        `Salary slip for ${selectedEmployee?.full_name || "employee"} is ready.`,
      );
      onGenerated();
      onClose();
      window.dispatchEvent(new Event("worksphere:notifications"));
    } catch (err) {
      setError((err as Error).message);
    } finally {
      setSaving(false);
    }
  };

  return (
    <Modal
      open={open}
      onClose={onClose}
      title="Generate payroll"
      description="Create a monthly salary slip. Net pay is calculated automatically."
      size="lg"
      footer={
        <>
          <Button variant="secondary" onClick={onClose} disabled={saving}>
            Cancel
          </Button>
          <Button type="submit" form="payroll-form" loading={saving}>
            Generate payslip
          </Button>
        </>
      }
    >
      <form id="payroll-form" className="modal-form" onSubmit={submit}>
        {error && <div className="form-alert">{error}</div>}
        <div className="form-grid">
          <Field label="Employee" htmlFor="payroll-employee" required>
            <Select
              id="payroll-employee"
              value={form.employee_id}
              onChange={(event) => selectEmployee(event.target.value)}
              required
            >
              <option value="">Select an employee</option>
              {employees.map((employee) => (
                <option key={employee.id} value={employee.id}>
                  {employee.full_name} · {employee.department}
                </option>
              ))}
            </Select>
          </Field>
          <Field label="Payroll month" htmlFor="payroll-month" required>
            <Input
              id="payroll-month"
              type="month"
              value={form.month}
              onChange={(event) => setForm((current) => ({ ...current, month: event.target.value }))}
              required
            />
          </Field>
          <Field
            label="Basic salary"
            htmlFor="payroll-basic"
            hint={selectedEmployee ? `Contract: ${formatCurrency(selectedEmployee.salary)}` : "Select an employee to prefill."}
            required
          >
            <Input
              id="payroll-basic"
              type="number"
              min={1}
              step="0.01"
              value={form.basic_salary}
              onChange={(event) => setForm((current) => ({ ...current, basic_salary: event.target.value }))}
              placeholder="95000"
              required
            />
          </Field>
          <Field label="Allowances" htmlFor="payroll-allowances">
            <Input
              id="payroll-allowances"
              type="number"
              min={0}
              step="0.01"
              value={form.allowances}
              onChange={(event) => setForm((current) => ({ ...current, allowances: event.target.value }))}
            />
          </Field>
          <Field label="Bonus" htmlFor="payroll-bonus">
            <Input
              id="payroll-bonus"
              type="number"
              min={0}
              step="0.01"
              value={form.bonus}
              onChange={(event) => setForm((current) => ({ ...current, bonus: event.target.value }))}
            />
          </Field>
          <Field label="Deductions" htmlFor="payroll-deductions">
            <Input
              id="payroll-deductions"
              type="number"
              min={0}
              step="0.01"
              value={form.deductions}
              onChange={(event) => setForm((current) => ({ ...current, deductions: event.target.value }))}
            />
          </Field>
        </div>

        <div className="payroll-total">
          <div>
            <span>Net pay</span>
            <strong>{formatCurrency(net)}</strong>
          </div>
          <span>Basic + allowances + bonus − deductions</span>
        </div>
      </form>
    </Modal>
  );
}

function StaffPayroll() {
  const toast = useToast();
  const now = new Date();
  const defaultMonthInput = `${now.getFullYear()}-${String(now.getMonth() + 1).padStart(2, "0")}`;
  const [monthInput, setMonthInput] = useState(defaultMonthInput);
  const [generateOpen, setGenerateOpen] = useState(false);
  const [payslipId, setPayslipId] = useState<number | null>(null);
  const [monthFilter, setMonthFilter] = useState("ALL");

  const resource = useResource(async () => {
    const [records, employees, summary] = await Promise.all([
      endpoints.payroll({ limit: 200 }),
      endpoints.employees({ limit: 100 }),
      endpoints.payrollSummary(monthKeyFromInput(monthInput)),
    ]);
    return { records, employees, summary };
  }, [monthInput]);

  const records = resource.data?.records || [];
  const employees = resource.data?.employees || [];
  const summary = resource.data?.summary;
  const employeeMap = new Map(employees.map((employee) => [employee.id, employee]));
  const months = useMemo(
    () => Array.from(new Set(records.map((record) => record.month))),
    [records],
  );
  const filteredRecords = useMemo(
    () =>
      monthFilter === "ALL"
        ? records
        : records.filter((record) => record.month === monthFilter),
    [records, monthFilter],
  );

  const exportCsv = () => {
    downloadCsv("worksphere-payroll.csv", [
      ["Month", "Employee", "Basic", "Allowances", "Bonus", "Deductions", "Gross", "Net"],
      ...filteredRecords.map((record) => [
        record.month,
        employeeMap.get(record.employee_id)?.full_name || `Employee #${record.employee_id}`,
        record.basic_salary,
        record.allowances,
        record.bonus,
        record.deductions,
        record.gross_salary,
        record.net_salary,
      ]),
    ]);
    toast.success("Payroll exported", `${filteredRecords.length} records saved as CSV.`);
  };

  if (resource.loading && !resource.data) {
    return <LoadingState label="Opening payroll…" />;
  }
  if (resource.error || !resource.data || !summary) {
    return <ErrorState message={resource.error || "Payroll unavailable"} onRetry={resource.refresh} />;
  }

  return (
    <div className="page-stack">
      <PageHeader
        eyebrow="Compensation"
        title="Payroll"
        description="Run salaries, inspect totals and keep every payslip close at hand."
        actions={
          <>
            <Button variant="secondary" icon={<FileSpreadsheet size={16} />} onClick={exportCsv}>
              Export
            </Button>
            <Button icon={<Plus size={16} />} onClick={() => setGenerateOpen(true)}>
              Generate payroll
            </Button>
          </>
        }
      />

      <div className="payroll-month-bar">
        <div>
          <span className="eyebrow">Summary period</span>
          <strong>{monthKeyFromInput(monthInput)}</strong>
        </div>
        <Input
          type="month"
          value={monthInput}
          onChange={(event) => {
            setMonthInput(event.target.value);
            setMonthFilter("ALL");
          }}
          aria-label="Payroll summary month"
        />
        <Button variant="ghost" size="sm" icon={<RefreshCw size={15} />} onClick={resource.refresh}>
          Refresh
        </Button>
      </div>

      <section className="stats-grid">
        <StatCard
          label="Net payroll"
          value={formatCurrency(summary.total_net, true)}
          meta={`${summary.employees_paid} salary slips`}
          icon={Banknote}
          tone="green"
        />
        <StatCard
          label="Gross pay"
          value={formatCurrency(summary.total_gross, true)}
          meta={`+ ${formatCurrency(summary.total_bonus)} bonus`}
          icon={BadgeIndianRupee}
          tone="teal"
        />
        <StatCard
          label="Allowances"
          value={formatCurrency(summary.total_allowances, true)}
          meta="This period"
          icon={WalletCards}
          tone="blue"
        />
        <StatCard
          label="Deductions"
          value={formatCurrency(summary.total_deductions, true)}
          meta="This period"
          icon={ReceiptText}
          tone="rose"
        />
      </section>

      <section className="card table-card">
        <div className="table-toolbar">
          <div className="toolbar-left">
            <h2 className="table-title">Payroll records</h2>
            <Select
              value={monthFilter}
              onChange={(event) => setMonthFilter(event.target.value)}
              aria-label="Filter payroll records by month"
              className="toolbar-select"
            >
              <option value="ALL">All months</option>
              {months.map((month) => (
                <option key={month} value={month}>
                  {month}
                </option>
              ))}
            </Select>
          </div>
          <span className="table-count">{filteredRecords.length} records</span>
        </div>

        {filteredRecords.length === 0 ? (
          <EmptyState
            icon={WalletCards}
            title="No payslips in this view"
            description="Generate payroll for an employee to get started."
            action={
              <Button size="sm" onClick={() => setGenerateOpen(true)}>
                Generate payroll
              </Button>
            }
          />
        ) : (
          <div className="table-scroll">
            <table className="data-table">
              <thead>
                <tr>
                  <th>Employee</th>
                  <th>Month</th>
                  <th>Basic</th>
                  <th>Allowances</th>
                  <th>Bonus</th>
                  <th>Deductions</th>
                  <th>Net pay</th>
                  <th />
                </tr>
              </thead>
              <tbody>
                {filteredRecords.map((record) => {
                  const employee = employeeMap.get(record.employee_id);
                  const name = employee?.full_name || `Employee #${record.employee_id}`;
                  return (
                    <tr key={record.id}>
                      <td>
                        <div className="person-cell">
                          <Avatar name={name} size="xs" />
                          <div>
                            <span className="person-name">{name}</span>
                            <span className="person-sub">{employee?.department || "—"}</span>
                          </div>
                        </div>
                      </td>
                      <td>
                        <Badge tone="slate">{record.month}</Badge>
                      </td>
                      <td>{formatCurrency(record.basic_salary)}</td>
                      <td>{formatCurrency(record.allowances)}</td>
                      <td>{formatCurrency(record.bonus)}</td>
                      <td className="negative">-{formatCurrency(record.deductions)}</td>
                      <td className="cell-strong">{formatCurrency(record.net_salary)}</td>
                      <td>
                        <button
                          type="button"
                          className="table-action"
                          onClick={() => setPayslipId(record.id)}
                          aria-label={`View payslip for ${name} ${record.month}`}
                        >
                          <Eye size={16} />
                        </button>
                      </td>
                    </tr>
                  );
                })}
              </tbody>
            </table>
          </div>
        )}
      </section>

      <GeneratePayrollModal
        open={generateOpen}
        onClose={() => setGenerateOpen(false)}
        employees={employees}
        defaultMonth={monthInput}
        onGenerated={resource.refresh}
      />
      <PayslipModal open={payslipId !== null} onClose={() => setPayslipId(null)} payrollId={payslipId} />
    </div>
  );
}

function EmployeePayroll() {
  const toast = useToast();
  const [payslipId, setPayslipId] = useState<number | null>(null);
  const [downloading, setDownloading] = useState<number | null>(null);

  const resource = useResource(async () => {
    const [records, profile] = await Promise.all([
      endpoints.myPayroll({ limit: 100 }),
      endpoints.myProfile(),
    ]);
    return { records, profile };
  }, []);

  if (resource.loading && !resource.data) {
    return <LoadingState label="Loading your payslips…" />;
  }
  if (resource.error || !resource.data) {
    return <ErrorState message={resource.error || "Payroll unavailable"} onRetry={resource.refresh} />;
  }

  const { records, profile } = resource.data;
  const latest = records[0];
  const year = new Date().getFullYear();
  const thisYear = records.filter((record) =>
    record.month.endsWith(String(year)),
  );
  const yearTotal = thisYear.reduce((sum, record) => sum + record.net_salary, 0);
  const average =
    records.length > 0 ? records.reduce((sum, record) => sum + record.net_salary, 0) / records.length : 0;

  const handleDownload = async (record: Payroll) => {
    setDownloading(record.id);
    try {
      const detail = await endpoints.payrollDetail(record.id);
      downloadPayslip(detail);
      toast.success("Payslip downloaded", `${record.month} salary slip saved.`);
    } catch (error) {
      toast.error("Download failed", (error as Error).message);
    } finally {
      setDownloading(null);
    }
  };

  return (
    <div className="page-stack">
      <PageHeader
        eyebrow="Compensation"
        title="Pay & payslips"
        description="Your salary history, transparent and ready to download."
        actions={
          <Button
            variant="secondary"
            icon={<RefreshCw size={16} />}
            onClick={resource.refresh}
            loading={resource.loading}
          >
            Refresh
          </Button>
        }
      />

      <section className="payroll-hero">
        <article className="card pay-hero-card">
          <span className="pay-hero-eyebrow">Latest net pay</span>
          <div className="pay-hero-value">
            {latest ? formatCurrency(latest.net_salary) : "—"}
          </div>
          <span className="pay-hero-month">{latest?.month || "No payslip generated yet"}</span>
          <div className="pay-hero-meta">
            <div>
              <span>Gross</span>
              <strong>{latest ? formatCurrency(latest.gross_salary) : "—"}</strong>
            </div>
            <div>
              <span>Deductions</span>
              <strong>{latest ? formatCurrency(latest.deductions) : "—"}</strong>
            </div>
            <div>
              <span>Bonus</span>
              <strong>{latest ? formatCurrency(latest.bonus) : "—"}</strong>
            </div>
          </div>
        </article>

        <article className="card pay-profile-card">
          <div className="card-heading">
            <div>
              <h2>Pay profile</h2>
              <p>{profile.designation} · {profile.department}</p>
            </div>
            <Avatar name={profile.full_name} size="md" />
          </div>
          <div className="pay-profile-rows">
            <div>
              <span>Monthly salary</span>
              <strong>{formatCurrency(profile.salary)}</strong>
            </div>
            <div>
              <span>Joined</span>
              <strong>{formatDate(profile.joining_date)}</strong>
            </div>
            <div>
              <span>Payslips issued</span>
              <strong>{records.length}</strong>
            </div>
            <div>
              <span>YTD net earnings</span>
              <strong>{formatCurrency(yearTotal)}</strong>
            </div>
          </div>
        </article>
      </section>

      <section className="stats-grid stats-grid-3">
        <StatCard label="Average net pay" value={formatCurrency(average, true)} meta="Across payslips" icon={Banknote} tone="green" />
        <StatCard label="YTD earnings" value={formatCurrency(yearTotal, true)} meta={`${thisYear.length} payslips in ${year}`} icon={WalletCards} tone="teal" />
        <StatCard label="Payslips issued" value={records.length} meta="All time" icon={ReceiptText} tone="purple" />
      </section>

      <section className="card table-card">
        <div className="card-heading card-heading-inset">
          <div>
            <h2>Payslip history</h2>
            <p>Every salary run, ready to download</p>
          </div>
          <Badge tone="slate">{records.length} payslips</Badge>
        </div>
        {records.length === 0 ? (
          <EmptyState
            icon={ReceiptText}
            title="No payslips yet"
            description="Once payroll is generated, your payslips will appear here."
          />
        ) : (
          <div className="table-scroll">
            <table className="data-table">
              <thead>
                <tr>
                  <th>Month</th>
                  <th>Basic</th>
                  <th>Allowances</th>
                  <th>Bonus</th>
                  <th>Deductions</th>
                  <th>Net pay</th>
                  <th />
                </tr>
              </thead>
              <tbody>
                {records.map((record) => (
                  <tr key={record.id}>
                    <td className="cell-strong">{record.month}</td>
                    <td>{formatCurrency(record.basic_salary)}</td>
                    <td>{formatCurrency(record.allowances)}</td>
                    <td>{formatCurrency(record.bonus)}</td>
                    <td className="negative">-{formatCurrency(record.deductions)}</td>
                    <td className="cell-strong">{formatCurrency(record.net_salary)}</td>
                    <td>
                      <div className="row-actions">
                        <button
                          type="button"
                          className="table-action"
                          onClick={() => setPayslipId(record.id)}
                          aria-label={`View payslip for ${record.month}`}
                        >
                          <Eye size={16} />
                        </button>
                        <button
                          type="button"
                          className="table-action"
                          onClick={() => handleDownload(record)}
                          disabled={downloading === record.id}
                          aria-label={`Download payslip for ${record.month}`}
                        >
                          <Download size={16} />
                        </button>
                      </div>
                    </td>
                  </tr>
                ))}
              </tbody>
            </table>
          </div>
        )}
      </section>

      <PayslipModal open={payslipId !== null} onClose={() => setPayslipId(null)} payrollId={payslipId} />
    </div>
  );
}

export function PayrollPage() {
  const { hasRole } = useAuth();
  return hasRole("HR", "ADMIN") ? <StaffPayroll /> : <EmployeePayroll />;
}
